#!/usr/bin/env bash
# Regenerates VERSIONS.md from what is installed (not typed by hand).
set -euo pipefail
cd "$(dirname "$0")/.."
{
echo "# VERSIONS.md"
echo
echo "Generated by scripts/write_versions.sh on $(date -u +%Y-%m-%dT%H:%MZ). Lockfiles (study/uv.lock, package-lock.json) are the source of truth."
echo
echo "## Toolchain"
echo '```'
echo "OS: $(. /etc/os-release && echo "$PRETTY_NAME") $(uname -m), kernel $(uname -r)"
echo "CPU/RAM: $(nproc) vCPU, $(free -g | awk '/Mem/{print $2}') GB"
echo "uv $(uv --version | cut -d' ' -f2)"
echo "Python $(cd study && uv run python -c 'import platform;print(platform.python_version())')"
echo "Node $(node --version)   npm $(npm --version)"
echo "Docker $(docker --version | sed 's/Docker version //')"
echo "Playwright $(npx playwright --version | sed 's/Version //'), Chromium $(node -e "import('playwright-core').then(async m=>{const b=await m.chromium.launch();console.log(b.version());await b.close()})")"
echo "actionlint $(actionlint -version | head -1)"
echo '```'
echo "Node 24 is the newest AWS Lambda managed Node.js runtime (nodejs24.x, GA; Node 26 is preview only; checked 2026-11-16, see PROBE.md/DECISIONS.md)."
echo
echo "## Python (study/uv.lock)"
echo '```'
cd study
uv run python - <<'PY'
import importlib.metadata as m
for n in ["duckdb","pandas","numpy","scipy","statsmodels","pyarrow","matplotlib","httpx","pytest","ruff"]:
    print(f"{n}=={m.version(n)}")
PY
cd ..
echo '```'
echo
echo "## Node (package-lock.json); direct dependencies, exact"
for w in api web infra; do
  echo "### $w"; echo '```'
  node -e "
const p=require('./$w/package.json');
for (const k of ['dependencies','devDependencies']) for (const [n,v] of Object.entries(p[k]||{})) console.log(n+'@'+v+(k==='devDependencies'?'  (dev)':''));
"
  echo '```'
done
echo "### root"; echo '```'
node -e "const p=require('./package.json');for(const [n,v] of Object.entries(p.devDependencies||{}))console.log(n+'@'+v+'  (dev)')"
echo '```'
} > VERSIONS.md
